#!/usr/bin/env python3
"""Generate onecore_uap_table.inc from the original Delphi OneCoreUAP.pas.

The table maps an API name to the api-set DLL that hosts it.  It is sorted by
API name so the C++ port can binary-search it at runtime.
"""

import re
import sys
from pathlib import Path

ENTRY_RE = re.compile(r"^\('(?P<api>[^']+)',\s*'(?P<dll>[^']+)'\),?\s*$")


def main() -> int:
    if len(sys.argv) != 3:
        print(f"usage: {sys.argv[0]} <OneCoreUAP.pas> <out.inc>", file=sys.stderr)
        return 2

    src = Path(sys.argv[1])
    dst = Path(sys.argv[2])

    entries = []
    for lineno, line in enumerate(src.read_text(encoding="utf-8").splitlines(), 1):
        match = ENTRY_RE.match(line.strip())
        if not match:
            continue
        entries.append((match.group("api"), match.group("dll")))

    if not entries:
        print("error: no entries found", file=sys.stderr)
        return 1

    if len({api for api, _ in entries}) != len(entries):
        print("warning: duplicate API names in source table", file=sys.stderr)

    entries.sort(key=lambda item: item[0])

    with dst.open("w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/gen_onecore_uap_table.py from OneCoreUAP.pas.\n")
        out.write("// Do not edit manually.\n")
        for api, dll in entries:
            out.write(f'{{"{api}", "{dll}"}},\n')

    print(f"wrote {len(entries)} entries to {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
